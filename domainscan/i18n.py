def valid_codes():
    return [code for code, _ in LANGUAGES]


def get(code, name, **values):
    table = STRINGS.get(code) or STRINGS["en"]
    text = table.get(name)
    if text is None:
        text = STRINGS["en"].get(name, name)
    if values:
        try:
            return text.format(**values)
        except Exception:
            return text
    return text


def section(code, name):
    return SECTION_NAMES.get(code, {}).get(name, name)


def config_dir(directory=None):
    return directory or os.path.join(os.path.expanduser("~"), ".domainscan")


def load_language(directory=None):
    try:
        with open(os.path.join(config_dir(directory), "language"), encoding="utf-8") as handle:
            code = handle.read().strip().lower()
    except Exception:
        return "en"
    if code in valid_codes():
        return code
    return "en"


def save_language(code, directory=None):
    if code not in valid_codes():
        code = "en"
    target = config_dir(directory)
    os.makedirs(target, exist_ok=True)
    with open(os.path.join(target, "language"), "w", encoding="utf-8") as handle:
        handle.write(code)
    return code
